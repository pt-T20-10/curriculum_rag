"""
State management for AI Textbook Generator using LangGraph.

This module defines the data contracts (Pydantic models) and state schema (TypedDict)
that all workflow nodes must adhere to. It serves as the single source of truth for
data structures flowing through the system.

Contents:
    Data models   — Pydantic schemas for structured LLM outputs (SubSection, Chapter,
                    CurriculumOutline). These enforce type safety on Planner output
                    before it enters the graph.
    Char targets  — SECTION_TYPE_CHAR_TARGETS map + get_char_target() accessor.
                    Single source of truth for section length targets consumed by
                    Writer (prompt injection) and Reviewer (quality gate).
    AgentState    — LangGraph TypedDict defining every field that flows through
                    the workflow. All nodes read from and write partial updates to
                    this shared state object.
    Helpers       — Utility functions shared across multiple agent nodes:
                    get_chapter_and_subsection(), clean_section_title(),
                    build_initial_state().
"""

import operator
import re
from typing import Any, List, TypedDict, Annotated, Optional
from pydantic import BaseModel, Field


# ============================================================================
# DATA MODELS — Pydantic schemas for structured LLM outputs
# ============================================================================

class SubSection(BaseModel):
    """
    Atomic unit of content: a single concept or topic within a chapter.

    Each subsection carries enough metadata for:
    - Researcher: `search_query` drives RAG retrieval
    - Writer:     `section_type` controls prose depth and char target
    - Reviewer:   `description` provides the quality evaluation baseline
    """

    title: str = Field(
        description="Title of the subsection (e.g., 'Variables in Python')"
    )
    description: str = Field(
        description="Brief description of what this subsection will cover"
    )
    search_query: str = Field(
        description="Optimized search query for RAG system to retrieve relevant information"
    )
    section_type: str = Field(
        default="medium",
        description=(
            "Depth level of the section — controls target character count:\n"
            "  'light'   : orientation, recap, bridge sections (1500-2500 chars)\n"
            "  'medium'  : explanations, demonstrations, illustrations (3000-4500 chars)\n"
            "  'deep'    : theory, analysis, complex techniques (4500-6500 chars)\n"
            "  'applied' : exercises, hands-on tasks, practice drills (2500-3500 chars)"
        )
    )


class Chapter(BaseModel):
    """
    Logical grouping of related subsections forming one textbook chapter.
    """

    title: str = Field(
        description="Title of the chapter (e.g., 'Getting Started with Python')"
    )
    subsections: List[SubSection] = Field(
        description="Ordered list of subsections within this chapter"
    )


class CurriculumOutline(BaseModel):
    """
    Master plan: complete hierarchical structure of the textbook.

    Generated by the Planner node as the first output of the workflow.
    Consumed by every downstream node (Researcher, Writer, Reviewer,
    Illustrator) to locate the current chapter and subsection.
    """

    topic: str = Field(
        description="The main topic of the curriculum"
    )
    chapters: List[Chapter] = Field(
        description="Ordered list of all chapters in the curriculum"
    )


# ============================================================================
# CHARACTER COUNT TARGET MAP
#
# Maps section_type → (min_chars, max_chars).
# Unit: characters (not words) — language-agnostic, correct for Vietnamese.
# ============================================================================

SECTION_TYPE_CHAR_TARGETS: dict[str, tuple[int, int]] = {
    "light":   (1500, 2500),
    "medium":  (3000, 4500),
    "deep":    (4500, 6500),
    "applied": (2500, 3500),
}

DEFAULT_CHAR_TARGET = (3000, 4500)

# ============================================================================
# CONTENT LEVEL SCALE FACTORS
# ============================================================================

CONTENT_LEVEL_SCALES: dict[str, float] = {
    "Ngắn":       0.55,
    "Trung Bình": 1.0,
    "Dài":        1.6,
    "Rất Dài":    2.3,
}

DEFAULT_CONTENT_LEVEL = "Trung Bình"
CONTENT_LEVEL_MIN_WORD_DEFAULTS: dict[str, int] = {
    "Ngắn": 300,
    "Trung Bình": 500,
    "Dài": 800,
    "Rất Dài": 1200,
}
CONTENT_LEVEL_MAX_WORD_DEFAULTS: dict[str, int] = {
    "Ngắn": 500,
    "Trung Bình": 800,
    "Dài": 1200,
    "Rất Dài": 1500,
}
CONTENT_LEVEL_MIN_WORD_KEYS: dict[str, str] = {
    "Ngắn": "CONTENT_LEVEL_SHORT_MIN_WORDS",
    "Trung Bình": "CONTENT_LEVEL_MEDIUM_MIN_WORDS",
    "Dài": "CONTENT_LEVEL_LONG_MIN_WORDS",
    "Rất Dài": "CONTENT_LEVEL_VERY_LONG_MIN_WORDS",
}
CONTENT_LEVEL_MAX_WORD_KEYS: dict[str, str] = {
    "Ngắn": "CONTENT_LEVEL_SHORT_MAX_WORDS",
    "Trung Bình": "CONTENT_LEVEL_MEDIUM_MAX_WORDS",
    "Dài": "CONTENT_LEVEL_LONG_MAX_WORDS",
    "Rất Dài": "CONTENT_LEVEL_VERY_LONG_MAX_WORDS",
}
CONTENT_WORD_TO_CHAR_RATIO_DEFAULTS: dict[str, float] = {
    "vi": 5.0,
    "en": 6.0,
}
CONTENT_WORD_TO_CHAR_RATIO_KEYS: dict[str, str] = {
    "vi": "CONTENT_WORD_TO_CHAR_RATIO_VI",
    "en": "CONTENT_WORD_TO_CHAR_RATIO_EN",
}


def _runtime_config_value(
    key: str,
    default: Any,
    advanced_config: dict[str, Any] | None = None,
) -> Any:
    if advanced_config and key in advanced_config:
        return advanced_config[key]
    try:
        from app.services.runtime_config import get_runtime_config

        value = get_runtime_config(key, required=False)
    except Exception:
        value = None
    return default if value is None else value


def _runtime_int(
    key: str,
    default: int,
    advanced_config: dict[str, Any] | None = None,
) -> int:
    try:
        return max(0, int(_runtime_config_value(key, default, advanced_config)))
    except (TypeError, ValueError):
        return default


def _runtime_float(
    key: str,
    default: float,
    advanced_config: dict[str, Any] | None = None,
) -> float:
    try:
        value = float(_runtime_config_value(key, default, advanced_config))
    except (TypeError, ValueError):
        return default
    return value if value > 0 else default


def _runtime_content_level_words(
    content_level: str,
    word_keys: dict[str, str],
    word_defaults: dict[str, int],
    advanced_config: dict[str, Any] | None = None,
) -> int:
    key = word_keys.get(content_level)
    default = word_defaults.get(content_level, 0)
    if not key:
        return default
    return _runtime_int(key, default, advanced_config)


def _runtime_word_to_char_ratio(
    language: str,
    advanced_config: dict[str, Any] | None = None,
) -> float:
    lang = (language or "vi").lower()
    if lang.startswith("en"):
        lang = "en"
    else:
        lang = "vi"
    key = CONTENT_WORD_TO_CHAR_RATIO_KEYS[lang]
    default = CONTENT_WORD_TO_CHAR_RATIO_DEFAULTS[lang]
    return _runtime_float(key, default, advanced_config)


def _words_to_chars(words: int, ratio: float) -> int:
    return int(round((words * ratio) / 50) * 50)


def get_char_target(
    section_type: str,
    content_level: str = DEFAULT_CONTENT_LEVEL,
    advanced_config: dict[str, Any] | None = None,
    language: str = "vi",
) -> tuple[int, int]:
    """
    Return (min_chars, max_chars) scaled by content_level.

    Args:
        section_type:  One of 'light', 'medium', 'deep', 'applied'.
        content_level: One of 'Ngắn', 'Trung Bình', 'Dài', 'Rất Dài'.
        language:      'vi' or 'en'; controls word-to-character conversion.

    Returns:
        (min_chars, max_chars) tuple, rounded to nearest 50.
    """
    base_min, base_max = SECTION_TYPE_CHAR_TARGETS.get(
        section_type.lower(), DEFAULT_CHAR_TARGET
    )
    scale = CONTENT_LEVEL_SCALES.get(content_level, 1.0)

    scaled_min = int(round(base_min * scale / 50) * 50)
    scaled_max = int(round(base_max * scale / 50) * 50)
    ratio = _runtime_word_to_char_ratio(language, advanced_config)
    min_words = _runtime_content_level_words(
        content_level,
        CONTENT_LEVEL_MIN_WORD_KEYS,
        CONTENT_LEVEL_MIN_WORD_DEFAULTS,
        advanced_config,
    )
    max_words = _runtime_content_level_words(
        content_level,
        CONTENT_LEVEL_MAX_WORD_KEYS,
        CONTENT_LEVEL_MAX_WORD_DEFAULTS,
        advanced_config,
    )

    if min_words:
        word_floor_chars = _words_to_chars(min_words, ratio)
        scaled_min = max(scaled_min, word_floor_chars)

    if max_words:
        if min_words and max_words < min_words:
            max_words = min_words
        word_ceiling_chars = _words_to_chars(max_words, ratio)
        scaled_max = min(scaled_max, max(word_ceiling_chars, scaled_min + 250))

    scaled_max = max(scaled_max, scaled_min + 250)
    return scaled_min, scaled_max


