# HELPERS
# ============================================================================

def get_chapter_and_subsection(
    curriculum: Any,
    chap_idx: int,
    sub_idx: int,
) -> tuple[Any, Any]:
    """
    Unified curriculum accessor supporting both Pydantic and dict formats.

    Args:
        curriculum: CurriculumOutline instance or equivalent dict.
        chap_idx:   0-indexed chapter position.
        sub_idx:    0-indexed subsection position within the chapter.

    Returns:
        (chapter, subsection) tuple.

    Raises:
        IndexError: If either index is out of bounds.
        KeyError:   If required keys are missing in dict format.
    """
    if isinstance(curriculum, CurriculumOutline):
        chapter = curriculum.chapters[chap_idx]
        return chapter, chapter.subsections[sub_idx]

    chapter = curriculum['chapters'][chap_idx]
    return chapter, chapter['subsections'][sub_idx]


def clean_section_title(title: str) -> str:
    """
    Strip structured prefixes from LLM-generated section titles.

    Handles patterns like:
        "Mục 1.2: Tên thật"   →  "Tên thật"
        "Phần 3: Nội dung"    →  "Nội dung"
        "Bài 2.1: Tiêu đề"    →  "Tiêu đề"

    Args:
        title: Raw section title string from curriculum.

    Returns:
        Cleaned title with prefix stripped, or original if no match.
    """
    return re.sub(r'^(Mục|Phần|Bài)\s+[\d.]+\s*:\s*', '', title).strip()


def build_initial_state(
    request: str,
    num_chapters: int = 3,
    enable_images: bool = True,
    min_chars_per_section: int = 0,
    max_subsections_per_chapter: int = 5,
    content_level: str = "Trung Bình",
    export_formats: list | None = None,
) -> dict:
    """
    Factory function for constructing the initial AgentState dict.

    Always use this instead of constructing state dicts manually at call sites.
    Ensures every required field is present with a validated default.

    Args:
        request:                     User's textbook topic (required).
        num_chapters:                Number of chapters to generate.
        enable_images:               Whether to insert images.
        min_chars_per_section:       Global char floor across all section types.
        max_subsections_per_chapter: Upper bound on subsections per chapter.
        content_level:               One of 'Ngắn', 'Trung Bình', 'Dài', 'Rất Dài'.
        export_formats:              List of export formats ('PDF', 'Word').

    Returns:
        Dict conforming to the AgentState TypedDict schema.
    """
    return {
        # Input
        "request": request,
        # Configuration
        "num_chapters":                num_chapters,
        "enable_images":               enable_images,
        "min_chars_per_section":       min_chars_per_section,
        "max_subsections_per_chapter": max_subsections_per_chapter,
        # Planning
        "curriculum":     None,
        "textbook_title": "",
        "preface_content": "",
        # Progress
        "current_chapter_index":    0,
        "current_subsection_index": 0,
        # Content
        "current_content": "",
        "final_content":   "",
        # Quality control
        "revision_number":       0,
        "review_feedback":       "",
        "chapter_header_written": False,
        "content_level": content_level,
        # RAG
        "rag_context": "",
        # Observability
        "messages": [],
        # Output
        "final_filepath":      None,
        "export_formats":      export_formats or ["Word"],
        "final_docx_filepath": None,
        # Validation
        "validation_failed":     False,
        "validation_reason":     "",
        "validation_suggestion": "",
        # Preview
        "chapter1_content": "",
    }